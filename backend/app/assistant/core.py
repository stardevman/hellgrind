"""Panel asistanının sohbet döngüsü (ağ yok). Claude çağrısı `app.live.assistant_llm.ask` içindedir (ücretli kilit,
bütçe rezervasyonu); testler ASK'i sahte istemciyle değiştirir.

Bir tur: yönetmenin mesajı eklenir → model çağrılır → araç istediyse araçlar çalışır, sonuçlar eklenir → model yeniden
çağrılır … en çok MAX_STEPS adım. Geçmiş yalnızca eklenir (düşünme blokları sohbete bağlıdır, değiştirilmez). Onay bekleyen
eylemlerin sonucu yönetmenin bir sonraki mesajına panel notu olarak eklenir.

Ücretsiz modda Claude çağrılmaz: asistan yerel bir durum özeti verir ve ücretli moda geçişin nasıl yapılacağını söyler."""
import json
import logging
import time
from decimal import Decimal

from sqlalchemy import func, select

from app.assistant import tools
from app.config import settings
from app.db import session_scope
from app.quality import directing

log = logging.getLogger("hellgrind.assistant")

MAX_STEPS = 10
MAX_USER_CHARS = 8000
PAGES_TR = {"script": "Senaryo", "voice": "Ses", "style": "Stil", "images": "Görsel", "assets": "Varlıklar",
            "board": "Storyboard", "edit": "Kurgu", "compare": "Karşılaştır", "color": "Renk", "deliver": "Teslim",
            "settings": "Ayarlar", "history": "Geçmiş"}

SYSTEM = """You are the production assistant built into Hell Grind, an animation studio panel. The director (the \
user) builds animated films and series here: a screenplay is split into shots, each shot is generated by a video model \
(H3 Max drafts, Seedance 2.5 finals, on fal.ai) from approved reference images, scored by a quality gate, then voiced, \
graded and assembled into the film. You help from start to finish: review results, find problems, explain them and fix \
them when asked.

Always answer in Turkish, in plain conversational sentences, briefly. Lead with the answer. Use shot codes (S013) the \
way the panel shows them.

How to work:
- Look before you judge: use project_overview, shot_details and view_shot (frames) instead of guessing. When the \
director says a shot has a problem, look at its frames first and say what you see.
- Fix text yourself when asked: update_shot changes the shot description, director note, duration or the director \
prompt. It is free and reversible and generates nothing. Say exactly what you changed.
- Anything that generates (rerender_shot, more_candidates, use_candidate) may cost money. Those tools never run \
directly: they show the director an approval card with the estimated cost. Propose them only when they are the right \
fix, give the reason and the estimate, and stop; you learn the result in the next message. Never claim something was \
generated before the result arrives.
- Generated videos carry no speech; narration and dialogue are added separately. The model invents whatever the \
shot text does not pin down, so fixes usually mean making the description concrete (who is where, what moves, what \
must NOT appear) rather than adding adjectives.
- Respect the budget shown in project_overview; mention when a fix would not fit.
- Panel notes in square brackets (e.g. [Panel notu: ...]) are written by the panel, not by the director.

""" + directing.ASSISTANT_GUIDE


def ASK(project_id: str, system: str, tool_defs: list, messages: list) -> dict:   # noqa: N802 — testler değiştirir
    from app.live.assistant_llm import ask              # ücretli: kilit + bütçe rezervasyonu orada
    return ask(project_id, system, tool_defs, messages)


# ---------- geçmiş ----------

def _expand(block, images: dict):
    """Kayıttaki görsel bloğunu (nesne deposu anahtarı) API'nin base64 görseline açar; diğer bloklar aynen."""
    if isinstance(block, dict):
        if block.get("type") == "image" and (block.get("source") or {}).get("type") == "hg_key":
            key = block["source"]["key"]
            if key not in images:
                import base64

                from app import storage
                images[key] = base64.b64encode(storage.read_bytes(key)).decode()
            return {"type": "image", "source": {"type": "base64", "media_type": block["source"].get("media_type",
                                                                                                   "image/jpeg"),
                                                "data": images[key]}}
        return {k: [_expand(x, images) for x in v] if k == "content" and isinstance(v, list) else v
                for k, v in block.items()}
    return block


def history(s, session_id: str) -> list:
    """API'ye gidecek mesajlar: ardışık aynı roller birleştirilir (yalnızca eklenen geçmiş, deterministik)."""
    from app.models import AssistantMessage
    images: dict = {}
    out: list = []
    for m in s.scalars(select(AssistantMessage).where(AssistantMessage.session_id == session_id)
                       .order_by(AssistantMessage.id)):
        content = [_expand(b, images) for b in m.content]
        if out and out[-1]["role"] == m.role:
            out[-1]["content"] = out[-1]["content"] + content
        else:
            out.append({"role": m.role, "content": content})
    return out


def _add(s, session_id: str, role: str, content: list, meta: dict | None = None) -> None:
    from app.models import AssistantMessage, AssistantSession
    s.add(AssistantMessage(session_id=session_id, role=role, content=content, meta=meta or {}))
    row = s.get(AssistantSession, session_id)
    row.updated_at = func.now()
    s.commit()


def _context_line(s, project_id: str, context: dict | None) -> str | None:
    """Yönetmenin panelde nerede olduğu: sayfa ve seçili çekim (modelin "bu çekim" demesini anlaması için)."""
    from app.models import Scene
    if not context:
        return None
    parts = []
    page = PAGES_TR.get(str(context.get("page") or ""))
    if page:
        parts.append(f"açık sayfa: {page}")
    sid = context.get("scene_id")
    if sid:
        try:
            sc = s.get(Scene, sid)
        except Exception:                               # noqa: BLE001 — bozuk kimlik bağlamı düşürür
            s.rollback()
            sc = None
        if sc is not None and str(sc.project_id) == project_id:
            parts.append(f"seçili çekim: {sc.scene_code}")
    return f"[Panel notu: {', '.join(parts)}]" if parts else None


def _decided_notes(s, session_id: str) -> list[str]:
    """Son mesajdan beri sonuçlanan eylemler (bir kez bildirilir)."""
    from app.models import AssistantAction
    notes = []
    for a in s.scalars(select(AssistantAction).where(AssistantAction.session_id == session_id,
                                                     AssistantAction.status.in_(("done", "failed", "declined")))
                       .order_by(AssistantAction.created_at)):
        result = dict(a.result or {})
        if result.get("noted"):
            continue
        if a.status == "declined":
            text = f"yönetmen reddetti: {a.summary}"
        elif a.status == "done":
            text = f"onaylandı ve başlatıldı: {a.summary} (aşamalar: {', '.join(result.get('stages') or []) or '—'})"
        else:
            text = f"onaylandı ama başlatılamadı: {a.summary} ({result.get('error')})"
        notes.append(f"[Panel notu: {text}]")
        a.result = {**result, "noted": True}
    return notes


# ---------- tur ----------

def start(session_id: str, text: str, context: dict | None = None) -> bool:
    """Yönetmenin mesajını kaydeder ve oturumu meşgul işaretler. Zaten yanıt yazılıyorsa False."""
    from app.models import AssistantSession
    text = (text or "").strip()[:MAX_USER_CHARS]
    with session_scope() as s:
        row = s.get(AssistantSession, session_id, with_for_update=True)
        if row.busy:
            return False
        row.busy, row.error = True, None
        if not row.title:
            row.title = text[:80]
        blocks = [{"type": "text", "text": n} for n in _decided_notes(s, session_id)]
        line = _context_line(s, str(row.project_id), context)
        if line:
            blocks.append({"type": "text", "text": line})
        blocks.append({"type": "text", "text": text})
        _add(s, session_id, "user", blocks, {"text": text, "context": context or {}})
    return True


def _offline(s, ctx: tools.Ctx, reason: str) -> str:
    """Claude çağrılamıyorsa yerel yanıt: neden ve projenin kısa durum özeti."""
    data = json.loads(tools.project_overview(s, ctx, {})[0]["text"])
    shots = data["shots"]
    done = sum(1 for x in shots if x["status"] == "done")
    issues = [x for x in shots if x["error"] or x["status"] in ("failed", "needs_review", "blocked")]
    b = data["budget"]
    lines = [reason, "",
             f"Yerel özet: {len(shots)} çekimin {done} tanesi tamam; harcama {b['spent_usd']:.2f} $ / {b['limit_usd']:.2f} $."]
    for x in issues[:6]:
        lines.append(f"- {x['shot']} ({x['status']}): {x['error'] or 'yönetmen incelemesi bekliyor'}")
    if len(issues) > 6:
        lines.append(f"- … ve {len(issues) - 6} çekim daha")
    return "\n".join(lines)


def run(session_id: str) -> None:
    """Sohbetin bir turunu tamamlar (arka planda). Hatalar oturuma yazılır; oturum her durumda serbest kalır."""
    from app.budget import killswitch
    from app.live import PaidCallBlocked
    from app.models import AssistantSession
    with session_scope() as s:
        row = s.get(AssistantSession, session_id)
        ctx = tools.Ctx(str(row.project_id), session_id, allow_all=row.allow_all)
    try:
        for step in range(MAX_STEPS):
            with session_scope() as s:
                messages = history(s, session_id)
            try:
                answer = ASK(ctx.project_id, SYSTEM, tools.TOOLS, messages)
            except (PaidCallBlocked, BudgetShort) as e:
                with session_scope() as s:
                    reason = (f"Asistan şu an Claude'a bağlanamıyor: {e}" if isinstance(e, BudgetShort) else
                              "Ücretsiz modda asistan Claude'u çağırmaz (Claude API ücretli). Ayarlar'dan ücretli moda "
                              "geçince projeyi inceleyip düzeltmeler yapabilirim." if settings.dry_run else
                              f"Claude API anahtarı tanımlı değil ya da kilitli: {e}")
                    _add(s, session_id, "assistant", [{"type": "text", "text": _offline(s, ctx, reason)}],
                         {"offline": True})
                return
            with session_scope() as s:
                _add(s, session_id, "assistant", answer["content"],
                     {"usd": answer.get("usd", 0), "model": answer.get("model"), "stop": answer.get("stop_reason"),
                      "input_tokens": answer.get("input_tokens"), "output_tokens": answer.get("output_tokens")})
                sess = s.get(AssistantSession, session_id)
                sess.spent_usd = Decimal(str(sess.spent_usd or 0)) + Decimal(str(answer.get("usd") or 0))
                s.commit()
            uses = [b for b in answer["content"] if isinstance(b, dict) and b.get("type") == "tool_use"]
            if answer.get("stop_reason") != "tool_use" or not uses:
                if answer.get("stop_reason") == "refusal":
                    with session_scope() as s:
                        _add(s, session_id, "assistant", [{"type": "text", "text": (
                            "Bu isteğe yanıt veremedim. Soruyu farklı biçimde yazar mısın?")}], {"refusal": True})
                return
            results, activity = [], []
            with session_scope() as s:
                for b in uses:
                    content, failed = tools.run(s, ctx, b["name"], b.get("input") or {})
                    results.append({"type": "tool_result", "tool_use_id": b["id"], "content": content,
                                    **({"is_error": True} if failed else {})})
                    activity.append({"tool": b["name"], "text": tools.activity(b["name"], b.get("input") or {}),
                                     "error": content[0].get("text") if failed else None})
                _add(s, session_id, "user", results, {"tools": activity, "actions": list(ctx.actions)})
            ctx.actions.clear()
        with session_scope() as s:
            _add(s, session_id, "assistant", [{"type": "text", "text": (
                "Bu turda çok adım attım ve durdum; devam etmemi istersen yaz.")}], {"limit": True})
    except killswitch.ProjectFrozen as e:
        _fail(session_id, f"Proje durduruldu ya da bütçe doldu; asistan yanıt veremedi ({e}).")
    except Exception as e:                              # noqa: BLE001 — panel hatayı gösterir
        log.exception("asistan turu başarısız")
        from app.live import redact
        _fail(session_id, redact(f"Asistan yanıt veremedi: {type(e).__name__}: {e}")[:600])
    finally:
        with session_scope() as s:
            row = s.get(AssistantSession, session_id)
            if row is not None:
                row.busy = False
                s.commit()


def _fail(session_id: str, message: str) -> None:
    from app.models import AssistantSession
    with session_scope() as s:
        row = s.get(AssistantSession, session_id)
        if row is not None:
            row.error = message
            s.commit()


class BudgetShort(Exception):
    """Kalan bütçe asistan çağrısının tahminine yetmiyor: rezervasyon denenmez (proje dondurulmasın)."""


