def view(s, session_id: str) -> dict:
    """Panelin sohbet görünümü: yalnızca okunacak metinler, araç etkinlikleri ve eylem kartları."""
    from app.models import AssistantAction, AssistantMessage, AssistantSession
    row = s.get(AssistantSession, session_id)
    actions = {str(a.id): a for a in s.scalars(select(AssistantAction).where(AssistantAction.session_id == session_id))}
    items: list = []
    for m in s.scalars(select(AssistantMessage).where(AssistantMessage.session_id == session_id)
                       .order_by(AssistantMessage.id)):
        meta = m.meta or {}
        at = m.created_at.timestamp() if m.created_at else time.time()
        if m.role == "user" and "text" in meta:
            items.append({"id": m.id, "role": "user", "text": meta["text"], "at": at})
        elif m.role == "user":
            for t in meta.get("tools") or []:
                items.append({"id": m.id, "role": "tool", "text": t["text"], "error": t.get("error"), "at": at})
            for aid in meta.get("actions") or []:
                a = actions.get(aid)
                if a is not None:
                    items.append({"id": m.id, "role": "action", "action": action_view(a), "at": at})
        else:
            text = "\n\n".join(b.get("text", "") for b in m.content if isinstance(b, dict) and b.get("type") == "text")
            if text.strip():
                items.append({"id": m.id, "role": "assistant", "text": text.strip(), "at": at,
                              "offline": bool(meta.get("offline"))})
    return {"id": session_id, "title": row.title, "busy": row.busy, "error": row.error, "allow_all": row.allow_all,
            "spent_usd": float(row.spent_usd or 0), "items": items}


def action_view(a) -> dict:
    return {"id": str(a.id), "tool": a.tool, "title": tools.PAID.get(a.tool, a.tool), "summary": a.summary,
            "estimate_usd": float(a.estimate_usd) if a.estimate_usd is not None else None, "status": a.status,
            "result": {k: v for k, v in (a.result or {}).items() if k != "noted"} or None,
            "scene_id": str(a.scene_id) if a.scene_id else None, "virtual": settings.dry_run}
